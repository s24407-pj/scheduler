-- Preserve the legacy users table as a migration archive. Authentication realms no longer share it.
CREATE TABLE customer_accounts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    phone_number VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A legacy staff-only row is not evidence of a customer identity. A reservation is evidence.
-- Fail safely rather than silently merge distinct legacy records during canonicalization.
DO $$ BEGIN
    IF EXISTS (
        SELECT '+' || ltrim(u.phone_number, '+') FROM users u
        WHERE NOT EXISTS (SELECT 1 FROM company_employees e WHERE e.user_id = u.id)
           OR EXISTS (SELECT 1 FROM reservations r WHERE r.customer_id = u.id)
        GROUP BY '+' || ltrim(u.phone_number, '+') HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'Canonical customer phone collision: operator reconciliation required before realm migration';
    END IF;
END $$;
INSERT INTO customer_accounts (id, phone_number, created_at)
SELECT u.id, '+' || ltrim(u.phone_number, '+'), coalesce(u.created_at, CURRENT_TIMESTAMP)
FROM users u
WHERE NOT EXISTS (SELECT 1 FROM company_employees e WHERE e.user_id = u.id)
   OR EXISTS (SELECT 1 FROM reservations r WHERE r.customer_id = u.id);
SELECT setval(pg_get_serial_sequence('customer_accounts', 'id'), greatest(coalesce((SELECT max(id) FROM users), 0) + 1, 1), false);

ALTER TABLE company_employees
    ADD COLUMN login_email VARCHAR(255),
    ADD COLUMN password_hash VARCHAR(255),
    ADD COLUMN first_name VARCHAR(100) NOT NULL DEFAULT '',
    ADD COLUMN last_name VARCHAR(100) NOT NULL DEFAULT '',
    ADD COLUMN contact_phone VARCHAR(20),
    ADD COLUMN photo_url VARCHAR(500),
    ADD COLUMN enabled BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN eligibility_mode VARCHAR(30) NOT NULL DEFAULT 'ALL_SERVICES';
UPDATE company_employees e SET
    login_email = lower(trim(u.email)), password_hash = u.password_hash,
    first_name = u.first_name, last_name = u.last_name,
    contact_phone = u.phone_number, photo_url = u.photo_url
FROM users u WHERE u.id = e.user_id;
-- Preserve legacy specific-service intent; an explicitly empty set is NONE after migration.
UPDATE company_employees e SET eligibility_mode = 'SPECIFIC_SERVICES'
WHERE EXISTS (SELECT 1 FROM employee_offerings a WHERE a.company_id = e.company_id AND a.employee_id = e.user_id);
CREATE UNIQUE INDEX staff_company_login_email ON company_employees (company_id, login_email);
ALTER TABLE company_employees ADD CONSTRAINT employee_eligibility_mode CHECK (eligibility_mode IN ('ALL_SERVICES','SPECIFIC_SERVICES'));

ALTER TABLE company_customers
    ADD COLUMN first_name VARCHAR(100),
    ADD COLUMN last_name VARCHAR(100),
    ADD COLUMN contact_email VARCHAR(255);
-- Arbitrary legacy notes/attachments are not sufficient evidence of a salon/customer relationship.
-- Keep them in a separate archive, without granting runtime access to the identity.
CREATE TABLE legacy_unverified_customer_profiles AS
SELECT c.* FROM company_customers c
WHERE NOT EXISTS (SELECT 1 FROM reservations r WHERE r.company_id = c.company_id AND r.customer_id = c.user_id);
DELETE FROM company_customers c
WHERE NOT EXISTS (SELECT 1 FROM reservations r WHERE r.company_id = c.company_id AND r.customer_id = c.user_id);
INSERT INTO company_customers (company_id, user_id)
SELECT DISTINCT r.company_id, r.customer_id FROM reservations r
ON CONFLICT (company_id, user_id) DO NOTHING;
UPDATE company_customers c SET first_name = u.first_name, last_name = u.last_name
FROM users u WHERE u.id = c.user_id;
-- Legacy email was a staff credential: never copy it into customer contact data.
ALTER TABLE company_customers ALTER COLUMN first_name SET NOT NULL;
ALTER TABLE company_customers ALTER COLUMN last_name SET NOT NULL;

-- New staff public identifiers are independent of customer accounts; preserve all existing identifiers.
CREATE SEQUENCE staff_public_id_seq;
SELECT setval('staff_public_id_seq', greatest(coalesce((SELECT max(id) FROM users), 0) + 1, 1), false);
