-- Resolve legacy customer collisions deterministically, keeping the earliest-created surviving appointment.
-- Losing records remain, with their original IDs/intervals and durable before/after audit.
DO $$ DECLARE appointment RECORD; BEGIN
    FOR appointment IN SELECT * FROM reservations WHERE status NOT IN ('CANCELLED','NO_SHOW')
        ORDER BY created_at NULLS LAST, id
    LOOP
        IF EXISTS (
            SELECT 1 FROM reservations r WHERE r.company_id = appointment.company_id
            AND r.customer_id = appointment.customer_id AND r.id <> appointment.id
            AND r.status NOT IN ('CANCELLED','NO_SHOW')
            AND (coalesce(r.created_at, 'infinity'::timestamptz), r.id) <
                (coalesce(appointment.created_at, 'infinity'::timestamptz), appointment.id)
            AND tstzrange(r.start_time,r.end_time) && tstzrange(appointment.start_time,appointment.end_time)
        ) THEN
            UPDATE reservations SET status = 'CANCELLED', version = version + 1,
                internal_cancellation_reason = 'Migracja: kolizja rezerwacji klienta; zachowano wcześniejszy rekord'
            WHERE id = appointment.id;
        END IF;
    END LOOP;
END $$;
