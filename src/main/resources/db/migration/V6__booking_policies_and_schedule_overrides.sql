 ADD COLUMN max_booking_advance_days INT NOT NULL DEFAULT 90 CHECK (max_booking_advance_days >= 0),
 ADD COLUMN max_future_customer_bookings INT NOT NULL DEFAULT 10 CHECK (max_future_customer_bookings >= 0);
CREATE TABLE employee_schedule_overrides (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL,
 employee_id BIGINT NOT NULL,
 schedule_date DATE NOT NULL,
 day_off BOOLEAN NOT NULL,
 start_time TIME,
 end_time TIME,
 UNIQUE(company_id, employee_id, schedule_date),
 FOREIGN KEY(company_id, employee_id) REFERENCES company_employees(company_id,user_id),
 CHECK ((day_off AND start_time IS NULL AND end_time IS NULL) OR
        (NOT day_off AND start_time IS NOT NULL AND end_time IS NOT NULL AND end_time > start_time))
);
