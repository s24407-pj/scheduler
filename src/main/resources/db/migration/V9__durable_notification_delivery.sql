CREATE TABLE notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(30) NOT NULL CHECK (kind IN ('CREATE','EDIT','RESTORE','CANCEL','BLOCK_SUMMARY','REMINDER')),
    reservation_id BIGINT REFERENCES reservations(id),
    company_id BIGINT NOT NULL REFERENCES companies(id),
    customer_id BIGINT NOT NULL REFERENCES customer_accounts(id),
    reservation_revision BIGINT,
    appointment_date DATE,
    state VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING','SENDING','ACCEPTED','TEMPORARY_FAILURE','AMBIGUOUS','PAUSED','DISCARDED')),
    attempts INT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at TIMESTAMPTZ NOT NULL,
    deadline TIMESTAMPTZ NOT NULL,
    run_token UUID,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK ((kind = 'BLOCK_SUMMARY' AND reservation_id IS NULL) OR (kind <> 'BLOCK_SUMMARY' AND reservation_id IS NOT NULL))
);
CREATE INDEX notification_due ON notification_deliveries(next_attempt_at) WHERE state IN ('PENDING','TEMPORARY_FAILURE');
CREATE UNIQUE INDEX notification_staff_revision ON notification_deliveries(reservation_id,reservation_revision,kind)
    WHERE kind IN ('CREATE','EDIT','RESTORE','CANCEL');
CREATE UNIQUE INDEX notification_reminder_date ON notification_deliveries(reservation_id,appointment_date)
    WHERE kind = 'REMINDER';
CREATE TABLE notification_delivery_reservations (
    delivery_id BIGINT NOT NULL REFERENCES notification_deliveries(id),
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    PRIMARY KEY(delivery_id,reservation_id)
);
